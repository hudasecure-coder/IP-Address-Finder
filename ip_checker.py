ip = input("Enter an IP address: ")
parts = ip.split(".")

if len(parts) != 4:
    print("Not valid: it needs exactly 4 numbers")
else:
    valid = True
    for part in parts:
        if not part.isdigit():
            print(part, "is not a number")
            valid = False
        elif int(part) > 255:
            print(part, "is too big (max 255)")
            valid = False

    if valid:
        print("Valid IP address")
        first = int(parts[0])
        second = int(parts[1])
        if first == 10:
            print("Private address")
        elif first == 192 and second == 168:
            print("Private address")
        elif first == 172 and 16 <= second <= 31:
            print("Private address")
        else:
            print("Public address")
    else:
        print("Not valid: each part must be a number from 0 to 255")